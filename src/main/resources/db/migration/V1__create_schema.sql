-- Schema inicial do portfolioService na modelagem nova.
--
-- A partir daqui o schema e responsabilidade das migrations: o Hibernate roda
-- com ddl-auto: validate e nao cria nem altera mais nada. Qualquer mudanca de
-- schema e um arquivo novo nesta pasta.
--
-- A modelagem nova nao tem mais a tabela asset. O identificador externo do
-- ativo (id do CoinGecko para cripto, symbol para acao) vive em
-- position.asset_id, junto com name/symbol/exchange copiados no momento da
-- compra. Os tipos abaixo espelham o que o Hibernate gerava, porque e contra
-- eles que o validate confere.

CREATE TABLE portfolio (
    id       varchar(255) NOT NULL,
    name     varchar(255),
    owner_id varchar(255),
    CONSTRAINT portfolio_pkey PRIMARY KEY (id)
);

CREATE TABLE position (
    id            bigint GENERATED BY DEFAULT AS IDENTITY,
    asset_id      varchar(255),
    average_price numeric(38,18),
    exchange      varchar(255),
    name          varchar(255),
    portfolio_id  varchar(255),
    quantity      numeric(38,18),
    symbol        varchar(255),
    type          varchar(255),
    CONSTRAINT position_pkey PRIMARY KEY (id),
    CONSTRAINT position_type_check CHECK (type IN ('CRIPTO', 'STOCK')),
    CONSTRAINT fk_position_portfolio FOREIGN KEY (portfolio_id) REFERENCES portfolio (id),
    -- Duas compras concorrentes do mesmo ativo no mesmo portfolio nao podem
    -- mais criar duas linhas: a segunda transacao esbarra aqui.
    CONSTRAINT uk_position_portfolio_asset UNIQUE (portfolio_id, asset_id)
);
